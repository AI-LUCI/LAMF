"""GUI installer + one-file EXE packaging tests.

Focus: the guarantees a PyInstaller one-file build can silently break.

  1. resource discovery works frozen and unfrozen;
  2. the payload staged out of the bundle is complete and excludes machine
     state (.venv, __pycache__, *.pyc);
  3. the GUI's choices map to a command line install.py actually accepts;
  4. END TO END: after staging out of a simulated ``_MEIxxxx`` directory, the
     launchers and harness registrations generated by the installer core point
     at the PERMANENT installation directory and contain no temp path.

No Tk main loop is started, so this runs headless in CI.
"""

from __future__ import annotations

import ast
import contextlib
import importlib.util
import io
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GUI_PATH = ROOT / "installer" / "windows_gui.py"
SPEC_PATH = ROOT / "installer" / "LAMF.spec"
BUILD_SCRIPT = ROOT / "installer" / "Build-LAMF-Exe.ps1"

_spec = importlib.util.spec_from_file_location("lamf_windows_gui", GUI_PATH)
gui = importlib.util.module_from_spec(_spec)
assert _spec and _spec.loader
# Register before exec: @dataclass resolves its own module via sys.modules.
sys.modules["lamf_windows_gui"] = gui
_spec.loader.exec_module(gui)


def quiet(fn, *args, **kwargs):
    """Run a chatty installer-core function without flooding the test output."""
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        return fn(*args, **kwargs)


def spec_constants() -> dict:
    """Module-level literals from LAMF.spec, read without executing PyInstaller."""
    tree = ast.parse(SPEC_PATH.read_text(encoding="utf-8"))
    out: dict = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        try:
            out[target.id] = ast.literal_eval(node.value)
        except ValueError:
            continue
    return out


def make_fake_payload(root: Path) -> Path:
    """A miniature package tree that carries the exclusions we care about."""
    (root / "installer").mkdir(parents=True)
    (root / "installer" / "install.py").write_text("# install\n", encoding="utf-8")
    (root / "installer" / "__pycache__").mkdir()
    (root / "installer" / "__pycache__" / "install.cpython-312.pyc").write_bytes(b"\x00")
    (root / "runtime" / "lamf").mkdir(parents=True)
    (root / "runtime" / "lamf" / "cli.py").write_text("# cli\n", encoding="utf-8")
    (root / "runtime" / "lamf" / "stale.pyc").write_bytes(b"\x00")
    (root / "runtime" / "requirements.txt").write_text("pyyaml\n", encoding="utf-8")
    (root / "runtime" / ".venv" / "Scripts").mkdir(parents=True)
    (root / "runtime" / ".venv" / "Scripts" / "python.exe").write_bytes(b"MZ")
    (root / "05_INTEGRATIONS").mkdir()
    (root / "05_INTEGRATIONS" / "README.md").write_text("x\n", encoding="utf-8")
    (root / "VERSION").write_text("2.0.0\n", encoding="utf-8")
    return root


